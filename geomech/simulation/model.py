"""The generated module as a model: its layout, the accelerations and state checks.

A model is a module written by ``geomech.codegen.generate_module`` from
``to_standard_form``: it defines ``LAYOUT``, ``mass``, ``bias``, ``input_matrix`` and
``kinematics`` (and ``energy`` with ``lagrangian=L``), with the equations
``mass @ a + bias + input_matrix @ u = 0`` (signs as in ``docs/conventions.md``).
"""

from __future__ import annotations

import weakref
from dataclasses import dataclass
from typing import Any

import numpy as np
from numpy.typing import ArrayLike

__all__ = ["accelerations", "check_state", "Model", "model_of"]

#: Tolerance of ``check_state``: |q| = 1, q·ω = 0, RᵀR = I and det R = 1.
STATE_TOL = 1e-9

#: ``accelerations`` raises above this condition number of the (projected) mass system.
MAX_COND = 1e12


@dataclass(frozen=True)
class _Var:
    """One configuration variable: its slots in ``state`` and in ``a``."""

    key: str  # printed configuration symbol (``q``, ``R``, ``x``)
    vel_key: str  # printed velocity symbol (``\\omega_{q}``, ``\\Omega_{R}``, ``\\dot x``)
    manifold: str  # "R", "R3", "S2", "SO3"
    cfg: slice
    vel: slice
    acc: slice


class Model:
    """The layout of a generated module, parsed once (``model_of`` caches it).

    ``variables`` lists the configuration variables in layout order; ``n_state``,
    ``n_config``, ``n_accel`` and ``n_inputs`` are the sizes of ``state``, of its
    configuration part, of ``a`` and of ``u``.
    """

    def __init__(self, module: Any):
        layout = getattr(module, "LAYOUT", None)
        if not isinstance(layout, dict):
            raise TypeError(
                "simulation: expected a module generated by geomech.codegen (with LAYOUT),"
                f" got {type(module).__name__}"
            )
        self.module = module
        self.layout = layout
        self.n_state = int(layout["n_state"])
        self.n_config = int(layout["n_config"])
        self.n_accel = int(layout["n_accel"])
        self.n_inputs = int(layout["n_inputs"])
        self.variables = [
            _Var(
                key=c["symbol"],
                vel_key=v["symbol"],
                manifold=c["manifold"],
                cfg=slice(*c["slice"]),
                vel=slice(*v["slice"]),
                acc=slice(*a["slice"]),
            )
            for c, v, a in zip(layout["configuration"], layout["velocity"], layout["acceleration"])
        ]
        self.s2 = [v for v in self.variables if v.manifold == "S2"]
        self.so3 = [v for v in self.variables if v.manifold == "SO3"]
        self.euclid = [v for v in self.variables if v.manifold in ("R", "R3")]

    def as_state(self, state, what="state") -> np.ndarray:
        x = np.asarray(state, dtype=float).reshape(-1)
        if x.size != self.n_state:
            raise ValueError(f"{what} must have {self.n_state} entries, got {x.size}")
        return x

    def as_input(self, u, what="u") -> np.ndarray:
        if u is None:
            return np.zeros(self.n_inputs)
        u = np.asarray(u, dtype=float).reshape(-1)
        if u.size != self.n_inputs:
            raise ValueError(f"{what} must have {self.n_inputs} entries, got {u.size}")
        return u

    def require(self, *names: str) -> Model:
        """Raise ``TypeError`` unless the module defines every function in *names*."""
        for name in names:
            if not callable(getattr(self.module, name, None)):
                hint = (
                    "; generate it from to_standard_form"
                    if name in ("mass", "bias", "input_matrix")
                    else "; generate it from linearize"
                    if name.endswith("_lin")
                    else ""
                )
                raise TypeError(f"simulation: the module has no {name}(){hint}")
        return self


_MODELS: weakref.WeakKeyDictionary = weakref.WeakKeyDictionary()


def model_of(module: Any) -> Model:
    """The ``Model`` of *module*, parsed once per module object."""
    try:
        model = _MODELS.get(module)
    except TypeError:  # not weak-referenceable: parse every time
        return Model(module)
    if model is None:
        model = _MODELS[module] = Model(module)
    return model


def solve_accelerations(
    model: Model, state: np.ndarray, u: np.ndarray, p: dict, check: bool = False
) -> np.ndarray:
    """The tangent-plane solve of ``accelerations`` on already validated arrays.

    A failed or non-finite solve always raises; with *check*, so does a condition number
    above ``MAX_COND`` (one SVD, so the integrators check only the initial state)."""
    mod = model.module
    A = mod.mass(state, p)
    b = -(mod.bias(state, p) + mod.input_matrix(state, p) @ u)
    for var in model.s2:
        q = state[var.cfg]
        rows = var.acc  # equations are ordered like the variables, so rows = a-slice
        P = np.eye(3) - np.outer(q, q)
        A[rows] = P @ A[rows]
        A[rows, var.acc] += np.outer(q, q)
        b[rows] = P @ b[rows]
    try:
        a = np.linalg.solve(A, b)
    except np.linalg.LinAlgError:
        a = None
    bad = a is None or not np.all(np.isfinite(a))
    if bad or check:
        with np.errstate(all="ignore"):
            cond = np.linalg.cond(A)
        if bad or not cond <= MAX_COND:
            what = "is singular" if not cond <= MAX_COND else "gives non-finite accelerations"
            raise np.linalg.LinAlgError(
                f"accelerations: the mass system {what} (condition number {cond:.3g})"
                f" at state {np.array2string(state, precision=6, max_line_width=1000)}"
            )
    assert a is not None
    return a


def accelerations(
    module: Any, state: ArrayLike, u: ArrayLike | None = None, p: dict | None = None
) -> np.ndarray:
    """The accelerations ``a`` of a generated standard-form module at ``(state, u)``.

    Solves ``mass @ a + bias + input_matrix @ u = 0``. Every S² equation is meaningful
    only on the tangent plane of its point ``q`` (``docs/conventions.md``), and its
    acceleration ``ω̇`` satisfies ``q · ω̇ = 0`` (from ``d/dt (q · ω) = 0`` with
    ``q̇ · ω = (ω × q) · ω = 0``). So each S² row block is replaced by ``P_q · row`` plus
    ``q qᵀ`` on its own ``ω̇`` column, with right-hand side ``−P_q (bias + G u)``,
    ``P_q = I − q qᵀ``; the couplings of that row to the other accelerations are
    projected too. The resulting square system is solved with ``np.linalg.solve``. This
    works whether the derived S² mass block is singular (``Hat(q) Hat(q) m l²``) or
    already full rank (``−m l² I``, when the engine used ``q · ω̇ = 0`` itself).

    Args:
        module: a module from ``generate_module`` of a ``to_standard_form`` result.
        state: the flat state (``LAYOUT``: configuration slots, then velocity slots).
        u: the inputs (``None`` for zeros).
        p: the parameters, keyed by printed symbol.

    Returns:
        The flat accelerations, ordered like ``LAYOUT["acceleration"]``.

    Raises:
        np.linalg.LinAlgError: the system is singular, i.e. its condition number exceeds
            ``MAX_COND`` (1e12); the message gives the condition number and the state.
            Examples: a zero mass, a singular inertia, a degenerate kinetic energy.
    """
    model = model_of(module).require("mass", "bias", "input_matrix")
    x, u = model.as_state(state), model.as_input(u)
    return solve_accelerations(model, x, u, p or {}, check=True)


def check_state(
    module: Any, state: ArrayLike, tol: float = STATE_TOL, what: str = "x0"
) -> np.ndarray:
    """Check that *state* lies on the state manifold of *module* and return it flat.

    Each S² point has unit norm and its velocity ``ω`` is orthogonal to it; each SO(3)
    point is orthogonal with determinant +1; every entry is finite. The tolerance is
    *tol* (1e-9). Raises ``ValueError`` naming the slot otherwise.
    """
    model = model_of(module)
    x = model.as_state(state, what)
    if not np.all(np.isfinite(x)):
        raise ValueError(f"{what}: non-finite entries {np.flatnonzero(~np.isfinite(x))}")
    for var in model.s2:
        q, w = x[var.cfg], x[var.vel]
        if abs(np.linalg.norm(q) - 1.0) > tol:
            raise ValueError(
                f"{what}: the S2 slot '{var.key}' must have unit norm, got"
                f" |{var.key}| = {np.linalg.norm(q):.12g}"
            )
        if abs(q @ w) > tol:
            raise ValueError(
                f"{what}: the velocity slot '{var.vel_key}' must be orthogonal to"
                f" '{var.key}', got {var.key}·{var.vel_key} = {q @ w:.3g}"
            )
    for var in model.so3:
        R = x[var.cfg].reshape(3, 3)
        err = np.linalg.norm(R.T @ R - np.eye(3))
        if err > tol:
            raise ValueError(
                f"{what}: the SO3 slot '{var.key}' must be orthogonal, got"
                f" |RᵀR − I| = {err:.3g} (row-major, 9 entries)"
            )
        det = np.linalg.det(R)
        if abs(det - 1.0) > tol:
            raise ValueError(
                f"{what}: the SO3 slot '{var.key}' must have determinant +1, got {det:.12g}"
            )
    return x
