"""The generated module as a model: its layout, the accelerations and state checks.

A model is a module written by ``geomech.codegen.generate_module`` from
``to_standard_form``: it defines ``LAYOUT``, ``mass``, ``bias``, ``input_matrix`` and
``kinematics`` (and ``energy`` with ``lagrangian=L``), with the equations
``mass @ a + bias + input_matrix @ u = 0`` (signs as in ``docs/conventions.md``).
"""

from __future__ import annotations

import weakref
from dataclasses import dataclass
from typing import Any

import numpy as np
from numpy.typing import ArrayLike

__all__ = ["accelerations", "check_state", "Model", "model_of"]

#: Tolerance of ``check_state``: |q| = 1, q·ω = 0 (S²), q·e = 0 (S¹), RᵀR = I and det R = 1.
STATE_TOL = 1e-9

#: ``accelerations`` raises above this condition number of the (projected, scaled and
#: row-equilibrated) mass system.
MAX_COND = 1e12


@dataclass(frozen=True)
class _Var:
    """One configuration variable: its slots in ``state`` and in ``a``."""

    key: str  # printed configuration symbol (``q``, ``R``, ``x``)
    vel_key: str  # printed velocity symbol (``\\omega_{q}``, ``\\Omega_{R}``, ``\\dot x``)
    manifold: str  # "R", "R3", "S1", "S2", "SO3"
    cfg: slice
    vel: slice
    acc: slice
    axis: str = ""  # printed axis of an S1 point (its key in p)


class Model:
    """The layout of a generated module, parsed once (``model_of`` caches it).

    ``variables`` lists the configuration variables in layout order; ``n_state``,
    ``n_config``, ``n_accel`` and ``n_inputs`` are the sizes of ``state``, of its
    configuration part, of ``a`` and of ``u``.
    """

    def __init__(self, module: Any):
        layout = getattr(module, "LAYOUT", None)
        if not isinstance(layout, dict):
            raise TypeError(
                "simulation: expected a module generated by geomech.codegen (with LAYOUT),"
                f" got {type(module).__name__}"
            )
        self.module = module
        self.layout = layout
        self.n_state = int(layout["n_state"])
        self.n_config = int(layout["n_config"])
        self.n_accel = int(layout["n_accel"])
        self.n_inputs = int(layout["n_inputs"])
        self.variables = [
            _Var(
                key=c["symbol"],
                vel_key=v["symbol"],
                manifold=c["manifold"],
                cfg=slice(*c["slice"]),
                vel=slice(*v["slice"]),
                acc=slice(*a["slice"]),
                axis=c.get("axis", ""),
            )
            for c, v, a in zip(layout["configuration"], layout["velocity"], layout["acceleration"])
        ]
        self.s1 = [v for v in self.variables if v.manifold == "S1"]
        self.s2 = [v for v in self.variables if v.manifold == "S2"]
        self.so3 = [v for v in self.variables if v.manifold == "SO3"]
        self.euclid = [v for v in self.variables if v.manifold in ("R", "R3")]

    def axis(self, var: _Var, p: dict | None, what: str = "simulation") -> np.ndarray:
        """The unit axis of the S¹ point *var*: ``p[var.axis]`` normalised. Raises
        ``KeyError`` naming the parameter when *p* lacks it and ``ValueError`` when it is
        not a nonzero finite 3-vector."""
        if p is None or var.axis not in p:
            raise KeyError(f"{what}: the S1 point '{var.key}' needs its axis '{var.axis}' in p")
        e = np.asarray(p[var.axis], dtype=float).reshape(-1)
        n = float(np.linalg.norm(e)) if e.size == 3 else 0.0
        if not (np.isfinite(n) and n > 0):
            raise ValueError(
                f"{what}: the axis '{var.axis}' of the S1 point '{var.key}' must be a nonzero"
                f" 3-vector, got {np.array2string(e, precision=6)}"
            )
        return e / n

    def kinematics(self, state, p) -> np.ndarray:
        """The module's ``kinematics`` at *state* (with *p* when it has an S¹ point)."""
        if self.s1:
            return self.module.kinematics(state, p)
        return self.module.kinematics(state)

    def as_state(self, state, what="state") -> np.ndarray:
        x = np.asarray(state, dtype=float).reshape(-1)
        if x.size != self.n_state:
            raise ValueError(f"{what} must have {self.n_state} entries, got {x.size}")
        return x

    def as_input(self, u, what="u") -> np.ndarray:
        """*u* as a flat float array of ``n_inputs`` finite entries (``None``: zeros).

        A scalar is accepted for a single input; an array of any other dimension than 1
        raises ``ValueError`` rather than being flattened (a ``(2, 2)`` array for four
        inputs is almost certainly a mistake). Non-finite entries raise ``ValueError``
        naming them."""
        if u is None:
            return np.zeros(self.n_inputs)
        arr = np.asarray(u, dtype=float)
        if arr.ndim > 1:
            raise ValueError(
                f"{what} must be a 1-D array of {self.n_inputs} entries, got shape {arr.shape}"
            )
        arr = arr.reshape(-1)
        if arr.size != self.n_inputs:
            raise ValueError(f"{what} must have {self.n_inputs} entries, got {arr.size}")
        if not np.all(np.isfinite(arr)):
            raise ValueError(
                f"{what} has non-finite entries at {np.flatnonzero(~np.isfinite(arr)).tolist()}:"
                f" {np.array2string(arr, precision=6)}"
            )
        return arr

    def require(self, *names: str) -> Model:
        """Raise ``TypeError`` unless the module defines every function in *names*."""
        for name in names:
            if not callable(getattr(self.module, name, None)):
                hint = (
                    "; generate it from to_standard_form"
                    if name in ("mass", "bias", "input_matrix")
                    else "; generate it from linearize"
                    if name.endswith("_lin")
                    else ""
                )
                raise TypeError(f"simulation: the module has no {name}(){hint}")
        return self


_MODELS: weakref.WeakKeyDictionary = weakref.WeakKeyDictionary()


def model_of(module: Any) -> Model:
    """The ``Model`` of *module*, parsed once per module object."""
    try:
        model = _MODELS.get(module)
    except TypeError:  # not weak-referenceable: parse every time
        return Model(module)
    if model is None:
        model = _MODELS[module] = Model(module)
    return model


def solve_accelerations(
    model: Model, state: np.ndarray, u: np.ndarray, p: dict, check: bool = False
) -> np.ndarray:
    """The tangent-plane solve of ``accelerations`` on already validated arrays.

    Each S² row block becomes ``P_q · row`` plus ``s q qᵀ`` on its own ``ω̇`` column,
    where ``s = ‖P_q D‖_F / √2`` and ``D`` is that row's diagonal mass block. Every row
    of the system is then divided by its largest entry (row equilibration) before the
    solve and before the condition number is taken; see ``accelerations``.

    A failed or non-finite solve always raises; with *check*, so does a condition number
    above ``MAX_COND`` (one SVD, so the integrators check only the initial state)."""
    mod = model.module
    A = mod.mass(state, p)
    b = -(mod.bias(state, p) + mod.input_matrix(state, p) @ u)
    for var in model.s2:
        q = state[var.cfg]
        rows = var.acc  # equations are ordered like the variables, so rows = a-slice
        qq = np.outer(q, q)
        P = np.eye(3) - qq
        A[rows] = P @ A[rows]
        # the tangent-plane inertia of this point: m l² for both -m l² I and
        # Hat(q) Hat(q) m l², whose projections are both -m l² P (‖P‖_F = √2)
        s = np.sqrt(np.sum(A[rows, var.acc] ** 2) / 2.0)
        A[rows, var.acc] += s * qq
        b[rows] = P @ b[rows]
    scale = np.abs(A).max(1)
    if not scale.all():
        scale[scale == 0] = 1.0  # a zero row stays zero: singular, and reported as such
    A /= scale[:, None]
    b /= scale
    try:
        a = np.linalg.solve(A, b)
    except np.linalg.LinAlgError:
        a = None
    bad = a is None or not np.all(np.isfinite(a))
    if bad or check:
        with np.errstate(all="ignore"):
            cond = np.linalg.cond(A)
        if bad or not cond <= MAX_COND:
            what = "is singular" if not cond <= MAX_COND else "gives non-finite accelerations"
            raise np.linalg.LinAlgError(
                f"accelerations: the mass system {what} (condition number {cond:.3g},"
                " after row equilibration)"
                f" at state {np.array2string(state, precision=6, max_line_width=1000)}"
            )
    assert a is not None
    return a


def accelerations(
    module: Any, state: ArrayLike, u: ArrayLike | None = None, p: dict | None = None
) -> np.ndarray:
    """The accelerations ``a`` of a generated standard-form module at ``(state, u)``.

    Solves ``mass @ a + bias + input_matrix @ u = 0``. Every S² equation is meaningful
    only on the tangent plane of its point ``q`` (``docs/conventions.md``), and its
    acceleration ``ω̇`` satisfies ``q · ω̇ = 0`` (from ``d/dt (q · ω) = 0`` with
    ``q̇ · ω = (ω × q) · ω = 0``). So each S² row block is replaced by ``P_q · row`` plus
    a multiple of ``q qᵀ`` on its own ``ω̇`` column, with right-hand side ``−P_q (bias + G u)``,
    ``P_q = I − q qᵀ``; the couplings of that row to the other accelerations are
    projected too. This works whether the derived S² mass block is singular
    (``Hat(q) Hat(q) m l²``) or already full rank (``−m l² I``, when the engine used
    ``q · ω̇ = 0`` itself).

    Scaling, so that the result does not depend on the units: the stabiliser is
    ``s q qᵀ`` with ``s = ‖P_q D‖_F / √2``, ``D`` the row's own diagonal mass block.
    Both forms of ``D`` project to ``−m l² P_q`` and ``‖P_q‖_F = √2``, so ``s = m l²``:
    the normal direction gets the same magnitude as the two tangent directions (for an
    anisotropic tangent inertia, the root mean square of the two). Then every row of the
    system and of the right-hand side is divided by its largest entry (row
    equilibration), and the system is solved with ``np.linalg.solve``. The condition
    number is taken on the equilibrated matrix, so a light link (``m₂/m₁ = 1e-9``) or a
    large one (1 t on a 100 km tether, SI units) is solved to round-off and accepted,
    while a kinetic energy that is degenerate for every parameter value still raises.

    Args:
        module: a module from ``generate_module`` of a ``to_standard_form`` result.
        state: the flat state (``LAYOUT``: configuration slots, then velocity slots).
        u: the inputs (``None`` for zeros).
        p: the parameters, keyed by printed symbol.

    Returns:
        The flat accelerations, ordered like ``LAYOUT["acceleration"]``.

    Raises:
        np.linalg.LinAlgError: the system is singular, i.e. its condition number after
            row equilibration exceeds ``MAX_COND`` (1e12); the message gives the
            condition number and the state. Examples: a zero mass, a singular
            inertia, a degenerate kinetic energy.
        ValueError: *u* has the wrong shape or non-finite entries.
    """
    model = model_of(module).require("mass", "bias", "input_matrix")
    x, u = model.as_state(state), model.as_input(u)
    return solve_accelerations(model, x, u, p or {}, check=True)


def check_state(
    module: Any,
    state: ArrayLike,
    tol: float = STATE_TOL,
    what: str = "x0",
    p: dict | None = None,
) -> np.ndarray:
    """Check that *state* lies on the state manifold of *module* and return it flat.

    Each S² point has unit norm and its velocity ``ω`` is orthogonal to it; each S¹ point
    has unit norm and, when *p* holds its axis ``e``, ``q·e = 0``; each SO(3) point is
    orthogonal with determinant +1; every entry is finite. The tolerance is *tol* (1e-9).
    Raises ``ValueError`` naming the slot otherwise.
    """
    model = model_of(module)
    x = model.as_state(state, what)
    if not np.all(np.isfinite(x)):
        raise ValueError(f"{what}: non-finite entries {np.flatnonzero(~np.isfinite(x))}")
    for var in model.s1:
        q = x[var.cfg]
        if abs(np.linalg.norm(q) - 1.0) > tol:
            raise ValueError(
                f"{what}: the S1 slot '{var.key}' must have unit norm, got"
                f" |{var.key}| = {np.linalg.norm(q):.12g}"
            )
        if p is not None and var.axis in p:
            e = model.axis(var, p, what)
            if abs(q @ e) > tol:
                raise ValueError(
                    f"{what}: the S1 slot '{var.key}' must be orthogonal to its axis"
                    f" '{var.axis}', got {var.key}·{var.axis} = {q @ e:.3g}"
                )
    for var in model.s2:
        q, w = x[var.cfg], x[var.vel]
        if abs(np.linalg.norm(q) - 1.0) > tol:
            raise ValueError(
                f"{what}: the S2 slot '{var.key}' must have unit norm, got"
                f" |{var.key}| = {np.linalg.norm(q):.12g}"
            )
        if abs(q @ w) > tol:
            raise ValueError(
                f"{what}: the velocity slot '{var.vel_key}' must be orthogonal to"
                f" '{var.key}', got {var.key}·{var.vel_key} = {q @ w:.3g}"
            )
    for var in model.so3:
        R = x[var.cfg].reshape(3, 3)
        err = np.linalg.norm(R.T @ R - np.eye(3))
        if err > tol:
            raise ValueError(
                f"{what}: the SO3 slot '{var.key}' must be orthogonal, got"
                f" |RᵀR − I| = {err:.3g} (row-major, 9 entries)"
            )
        det = np.linalg.det(R)
        if abs(det - 1.0) > tol:
            raise ValueError(
                f"{what}: the SO3 slot '{var.key}' must have determinant +1, got {det:.12g}"
            )
    return x
